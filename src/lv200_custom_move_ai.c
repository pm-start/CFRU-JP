bool8 AIMoveInMoveset(u16 baseMove, u8 bank)
{
	for (u8 i = 0; i < MAX_MON_MOVES; ++i)
	{
		u16 move = gBattleMons[bank].moves[i];
		if (move != MOVE_NONE && (Lv200MoveAIBase(move) == baseMove || EffectiveMove(move) == baseMove)) //AI用の近い技と、効果元（ベノムシャワー＝ベノムショック等）の両方を見る
			return TRUE;
	}

	return FALSE;
}
